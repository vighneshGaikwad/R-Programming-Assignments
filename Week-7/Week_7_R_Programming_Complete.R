# 8. DATE SEQUENCES
# =========================================================

# Sequence of first day of years
seq(
  as.Date("2010-01-01"),
  as.Date("2017-01-01"),
  by = "years"
)

# Sequence of days
seq(
  as.Date("2017-01-01"),
  by = "days",
  length = 6
)

# Sequence of months
seq(
  as.Date("2017-01-01"),
  by = "months",
  length = 6
)

# Sequence by years
seq(
  as.Date("2017-01-01"),
  by = "years",
  length = 6
)

# Reverse sequence of dates by month
startdate = as.Date("2016-1-1")
enddate = as.Date("2017-1-1")

out = seq(
  enddate,
  startdate,
  by = "-1 month"
)

out


